/** 給定元素陣列，回傳 { Symbol -> group label } 的 mapping，供 GroupBox 使用 */
export function buildTableGroups(elements) {
  const map = {}
  for (const e of elements) {
    const pos = POSITION[Number(e.AtomicNumber)]
    if (!pos) continue
    const [row, col] = pos
    map[e.Symbol] = row === 9 ? 'Lanthanides'
                  : row === 10 ? 'Actinides'
                  : (COL_LABEL[col] || `Group ${col}`)
  }
  return map
}

